const std = @import("std");
const testing = std.testing;
const ingestion = @import("ingestion");
const mtx = ingestion.transcriptomics.mtx;

// ─── Happy Path ───────────────────────────────────────────────────────────────

test "mtx: parse valid 2x2 sparse matrix" {
    const data =
        "%%MatrixMarket matrix coordinate real general\n" ++
        "% comment\n" ++
        "2 2 2\n" ++
        "1 1 1.0\n" ++
        "2 2 2.0\n";
    const parser = mtx.MtxParser.init(testing.allocator);
    var sparse = try parser.parseSparseMmap(data);
    defer sparse.deinit();
    try testing.expectEqual(@as(usize, 2), sparse.rows);
    try testing.expectEqual(@as(usize, 2), sparse.cols);
    try testing.expectEqual(@as(f64, 1.0), sparse.data[0]);
    try testing.expectEqual(@as(f64, 2.0), sparse.data[1]);
}

test "mtx: indptr boundaries are correct for single-col matrix" {
    const data =
        "%%MatrixMarket matrix coordinate real general\n" ++
        "3 1 3\n" ++
        "1 1 10.0\n" ++
        "2 1 20.0\n" ++
        "3 1 30.0\n";
    const parser = mtx.MtxParser.init(testing.allocator);
    var sparse = try parser.parseSparseMmap(data);
    defer sparse.deinit();
    // Every row has exactly 1 entry: indptr = [0,1,2,3]
    try testing.expectEqual(@as(u32, 0), sparse.indptr[0]);
    try testing.expectEqual(@as(u32, 1), sparse.indptr[1]);
    try testing.expectEqual(@as(u32, 2), sparse.indptr[2]);
    try testing.expectEqual(@as(u32, 3), sparse.indptr[3]);
}

test "mtx: comment-only lines after header are skipped" {
    const data =
        "%%MatrixMarket matrix coordinate real general\n" ++
        "% generated by test\n" ++
        "% another comment\n" ++
        "2 2 1\n" ++
        "1 1 5.5\n";
    const parser = mtx.MtxParser.init(testing.allocator);
    var sparse = try parser.parseSparseMmap(data);
    defer sparse.deinit();
    try testing.expectEqual(@as(f64, 5.5), sparse.data[0]);
}

