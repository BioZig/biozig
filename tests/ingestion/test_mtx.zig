// ─── Data Integrity ───────────────────────────────────────────────────────────

test "mtx: entry count mismatch (fewer entries than declared)" {
    const data =
        "%%MatrixMarket matrix coordinate real general\n" ++
        "3 3 5\n" ++
        "1 1 1.0\n" ++  // only 1 entry but declared 5
        "\n";
    const parser = mtx.MtxParser.init(testing.allocator);
    try testing.expectError(error.MtxEntryCountMismatch, parser.parseSparseMmap(data));
}

test "mtx: row index out of bounds (row > declared rows)" {
    const data =
        "%%MatrixMarket matrix coordinate real general\n" ++
        "2 2 1\n" ++
        "5 1 1.0\n"; // row 5 declared but only 2 rows exist
    const parser = mtx.MtxParser.init(testing.allocator);
    try testing.expectError(error.MtxIndexOutOfBounds, parser.parseSparseMmap(data));
}

test "mtx: col index out of bounds (col > declared cols)" {
    const data =
        "%%MatrixMarket matrix coordinate real general\n" ++
        "2 2 1\n" ++
        "1 9 1.0\n"; // col 9 when only 2 cols declared
    const parser = mtx.MtxParser.init(testing.allocator);
    try testing.expectError(error.MtxIndexOutOfBounds, parser.parseSparseMmap(data));
}

test "mtx: row index = 0 is invalid (MTX is 1-based)" {
    const data =
        "%%MatrixMarket matrix coordinate real general\n" ++
        "2 2 1\n" ++
        "0 1 1.0\n";
    const parser = mtx.MtxParser.init(testing.allocator);
    try testing.expectError(error.MtxIndexOutOfBounds, parser.parseSparseMmap(data));
}

// ─── Sparse -> Dense Conversion ───────────────────────────────────────────────

test "mtx: parseDenseMmap produces correct dense matrix from sparse" {
    const data =
        "%%MatrixMarket matrix coordinate real general\n" ++
        "2 2 2\n" ++
        "1 1 3.0\n" ++
        "2 2 7.0\n";
    const parser = mtx.MtxParser.init(testing.allocator);
    var dense = try parser.parseDenseMmap(data);
    defer dense.deinit();
    try testing.expectEqual(@as(f64, 3.0), dense.get(0, 0));
    try testing.expectEqual(@as(f64, 0.0), dense.get(0, 1));
    try testing.expectEqual(@as(f64, 0.0), dense.get(1, 0));
    try testing.expectEqual(@as(f64, 7.0), dense.get(1, 1));
}
